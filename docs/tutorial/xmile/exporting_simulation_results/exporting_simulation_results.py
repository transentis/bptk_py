@app.cell
def _(bptk, equations, pd, scenario_manager, scenarios):
    # create a new dataframe with a column for each scenario, indexed by time and indicator
    indicator_dfs = []
    for scenario_no, scenario_1 in enumerate(scenarios):
        scenario_dfs_1 = []
        for equation in equations:
            df_2 = bptk.plot_scenarios(scenario_managers=[scenario_manager], scenarios=[scenario_1], equations=[equation], return_df=True)  # loop through the equations
            df_2.rename(columns={equation: scenario_1}, inplace=True)
            if scenario_no is len(scenarios) - 1:  # add a column which will contain the name of the indicator
                df_2['indicator'] = [equation] * len(df_2.index)
                df_2['time'] = df_2.index
            scenario_dfs_1 = scenario_dfs_1 + [df_2]
        indicators_scenario_tab = pd.concat(scenario_dfs_1, axis=0, ignore_index=True, sort=False)
        indicator_dfs = indicator_dfs + [indicators_scenario_tab]
    indicators_tab = pd.concat(indicator_dfs, axis=1, sort=False)
    #concatenate all the scenario columns (i.e. along axis 1)
    indicators_tab.index.name = 'id'  # conacate the indicators for the scenario (i.e. along axis 0)  # create a new column which will contain the time step (which won't be a unique index anymore, as we are concatenating many scenarios)
    indicators_tab.iloc[0:10]
    return


